GCODE = (b'; HEADER_BLOCK_START\n; generated by AnycubicSlicerNext 2.0.0.3\n'
         b'; total layer number: 460\nG9111 bedTemp=60 extruderTemp=220\n'
         b'G1 X1 Y2 E0.01\r\n; printer_model = Anycubic Kobra X\n')


def config():
    return SimpleNamespace(host="127.0.0.1", http_port=18910, printer_id="testdevice", type_id=20030)


class FakeMQTT:
    before = {"state": "free", "project": None, "model": "Anycubic Kobra X", "version": "2.0.2.2",
              "urls": {"fileUploadurl": "http://127.0.0.1:18910/gcode_upload?s=testtoken"}}
    listing = []
    posted = False
    calls = []
    name = "agent-test.gcode"
    def __init__(self, config):
        pass
    def __enter__(self):
        return self
    def __exit__(self, *args):
        pass
    def query(self, kind, action="query", data=None):
        self.calls.append((kind, action))
        if kind == "info":
            d = self.before
        elif action == "listLocal":
            d = {"records": [{"filename": self.name, "size": len(GCODE), "is_dir": False}] if self.posted else self.listing}
        elif action == "fileDetails":
            d = {"filename": self.name, "file_details": {"file_size": len(GCODE),
                 "layer_count": 460, "printer_model": "Anycubic Kobra X"}}
        else:
            raise AssertionError("Unexpected query")
        return {"code": 200, "data": d}


class UploadTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.root = Path(self.tmp.name)
        self.file = self.root / "test.gcode"
        self.file.write_bytes(GCODE)
        self.sha = hashlib.sha256(GCODE).hexdigest()
        FakeMQTT.posted = False
        FakeMQTT.listing = []
        FakeMQTT.calls = []
        FakeMQTT.before = {"state": "free", "project": None, "model": "Anycubic Kobra X", "version": "2.0.2.2",
                           "urls": {"fileUploadurl": "http://127.0.0.1:18910/gcode_upload?s=testtoken"}}
    def tearDown(self):
        self.tmp.cleanup()
    def run_upload(self):
        return execute(config(), self.file, self.sha, self.root / "state", "agent-test.gcode")
    def test_multipart_preserves_exact_bytes_without_print_flag(self):
        body = multipart(GCODE, "agent-test.gcode", "boundary")
        payload = body.split(b"Content-Type: application/octet-stream\r\n\r\n", 1)[1].rsplit(b"\r\n--boundary--\r\n", 1)[0]
        self.assertEqual(payload, GCODE)
        self.assertNotIn(b'name="print"', body)
    def test_injection_and_wrong_printer_rejected(self):
        for name in ['../test.gcode', 'a"\r\nInjected: x.gcode', 'a b.gcode']:
            with self.assertRaises(ProtocolError): describe(self.file, name)
        self.file.write_bytes(GCODE.replace(b"Anycubic Kobra X", b"Other printer"))
        with self.assertRaises(ProtocolError): describe(self.file)
    def test_upload_url_restricted(self):
        good = "http://127.0.0.1:18910/gcode_upload?s=abcd"
        self.assertEqual(upload_target(config(), good), "/gcode_upload?s=abcd")
        for url in [good.replace("127.0.0.1", "evil.example"), good.replace("18910", "80"),
                    good + "&print=true", good.replace("gcode_upload", "ctrl"), good + "#fragment"]:
            with self.assertRaises(ProtocolError): upload_target(config(), url)
    def test_hash_mismatch_before_network(self):
        with patch("kobra_lan.upload.MQTT") as mqtt:
            with self.assertRaises(ProtocolError): execute(config(), self.file, "0" * 64, self.root)
            mqtt.assert_not_called()
    def test_dry_run_has_no_network(self):
        with patch("kobra_lan.cli.Config.load") as cfg, contextlib.redirect_stdout(io.StringIO()):
            self.assertEqual(main(["upload", str(self.file), "--name", "agent-test.gcode"]), 0)
            cfg.assert_not_called()
    def test_timeout_attempt_cannot_be_replayed(self):
        with patch("kobra_lan.upload.MQTT", FakeMQTT), patch("kobra_lan.upload.post_once", side_effect=socket.timeout) as post:
            with self.assertRaises(ProtocolError): self.run_upload()
            with self.assertRaises(ProtocolError): self.run_upload()
            self.assertEqual(post.call_count, 1)
        receipts = list((self.root / "state").rglob("*.json"))
        self.assertEqual(json.loads(receipts[0].read_text())["status"], "uncertain_no_retry")
    def test_success_is_verified_and_cannot_be_replayed(self):
        def uploaded(*args):
            FakeMQTT.posted = True
            return 200, {"code": 200, "data": {}, "secret": "not-persisted"}
        with patch("kobra_lan.upload.MQTT", FakeMQTT), patch("kobra_lan.upload.post_once", side_effect=uploaded) as post:
            receipt = self.run_upload()
            self.assertEqual(receipt["status"], "uploaded_verified_by_listing_and_metadata")
            self.assertNotIn("not-persisted", json.dumps(receipt))
            self.assertFalse(receipt["starts_print"])
            with self.assertRaises(ProtocolError): self.run_upload()
            self.assertEqual(post.call_count, 1)
            self.assertNotIn(("print", "start"), FakeMQTT.calls)
    def test_busy_device_has_no_upload(self):
        FakeMQTT.before["state"] = "busy"
        with patch("kobra_lan.upload.MQTT", FakeMQTT), patch("kobra_lan.upload.post_once") as post:
            with self.assertRaises(ProtocolError): self.run_upload()
            post.assert_not_called()
    def test_existing_remote_file_not_overwritten(self):
        FakeMQTT.listing = [{"filename": "agent-test.gcode", "size": len(GCODE)}]
        with patch("kobra_lan.upload.MQTT", FakeMQTT), patch("kobra_lan.upload.post_once") as post:
            with self.assertRaises(ProtocolError): self.run_upload()
            post.assert_not_called()
    def test_http_transport_sends_once_and_does_not_redirect(self):
        response = SimpleNamespace(status=302, read=lambda n: b'{}')
        conn = unittest.mock.Mock()
        conn.getresponse.return_value = response
        with patch("kobra_lan.upload.http.client.HTTPConnection", return_value=conn):
            with self.assertRaises(ProtocolError): post_once(config(), "/gcode_upload?s=test", GCODE, "agent-test.gcode")
        self.assertEqual(conn.request.call_count, 1)
        self.assertEqual(conn.request.call_args.args[0], "POST")
        self.assertEqual(conn.request.call_args.kwargs["headers"]["X-File-Length"], str(len(GCODE)))


class MQTTTests(unittest.TestCase):
    def test_framing_variable_length(self):
        self.assertEqual(packet(0x30, b"x" * 128)[:3], b"\x30\x80\x01")
    def test_fragmented_receive(self):
        class Sock:
            chunks = iter(bytes([x]) for x in packet(0x30, b"hello"))
            def settimeout(self, value): pass
            def recv(self, size): return next(self.chunks)
        mqtt = MQTT(config());mqtt.sock = Sock()
        self.assertEqual(mqtt.receive(time.monotonic() + 2), (0x30, b"hello"))
    def test_start_not_allowed(self):
        with self.assertRaises(ProtocolError): MQTT(config()).query("print", "start")
    def test_fresh_report_requires_correlated_ack(self):
        mqtt = MQTT(config())
        mqtt.sock = unittest.mock.Mock()
        requests = []
        def receive(deadline):
            if not requests:
                raw = mqtt.sock.sendall.call_args.args[0]
                pos = raw.index(b'{');payload = json.loads(raw[pos:]);mid = payload['msgid'];ts = payload['timestamp']
                requests.extend([
                    {"type": "info", "msgid": "unrelated", "timestamp": ts, "data": {"state": "stale"}},
                    {"code": 0, "msgid": mid},
                    {"type": "info", "msgid": "server-generated", "timestamp": ts - 1000, "data": {"state": "stale"}},
                    {"type": "info", "msgid": "server-generated", "timestamp": ts, "data": {"state": "free"}}])
            result = requests.pop(0)
            topic = "root/response" if 'type' not in result else "root/info/report"
            return 0x30, string(topic) + json.dumps(result).encode()
        with patch.object(mqtt, "receive", side_effect=receive):
            self.assertEqual(mqtt.query("info")["data"]["state"], "free")
    def test_changed_tls_pin_blocks_credentials(self):
        cfg = config();cfg.mqtt_port = 9883;cfg.client_cert = "cert";cfg.client_key = "key";cfg.tls_sha256 = "0" * 64
        ctx = unittest.mock.Mock();sock = unittest.mock.Mock();ctx.wrap_socket.return_value = sock
        sock.getpeercert.return_value = b"unexpected cert"
        with patch("kobra_lan.mqtt.ssl.SSLContext", return_value=ctx), patch("kobra_lan.mqtt.socket.create_connection"):
            with self.assertRaises(ProtocolError): MQTT(cfg).__enter__()
        sock.sendall.assert_not_called()
    def test_wrong_file_report_rejected(self):
        client = unittest.mock.Mock();client.query.return_value = {"code": 200, "data": {"filename": "other.gcode"}}
        with self.assertRaises(ProtocolError): file_details(client, "expected.gcode")


