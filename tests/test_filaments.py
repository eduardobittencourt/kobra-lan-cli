class NormalizeColorTests(unittest.TestCase):
    def test_valid_rgb_and_rgba(self):
        self.assertEqual(normalize_color([0, 255, 128]), ([0, 255, 128], "#00FF80"))
        self.assertEqual(normalize_color([138, 148, 158, 255]), ([138, 148, 158], "#8A949E"))

    def test_invalid_colors_rejected(self):
        for bad in (
            "#00FF00",
            [],
            [0, 255],
            [0, 255, 0, 255, 0],
            [-1, 0, 0],
            [0, 256, 0],
            [True, 0, 0],
            [0, False, 0],
            [0.0, 0, 0],
            ["0", "0", "0"],
            None,
        ):
            with self.subTest(bad=bad), self.assertRaises(ProtocolError):
                normalize_color(bad)


class InspectGcodeFilamentsTests(unittest.TestCase):
    def test_single_color_paint_index_zero(self):
        data = (
            b"; generated by AnycubicSlicerNext 2.0.0.6\n"
            b'; paint_info = [{"paint_index":0,"material_type":"PLA","paint_color":[138,148,158]}]\n'
            b"T0\nG1 X1 Y1 E0.1\n"
            b"; filament used [g] = 4.25\n"
            b"; total filament used [g] = 4.25\n"
            b'; paint_info = [{"paint_index":0,"material_type":"PLA","paint_color":[138,148,158]}]\n'
        )
        info = inspect_gcode_filaments(data)
        self.assertTrue(info["paint_info_present"])
        self.assertEqual(info["filament_count"], 1)
        self.assertFalse(info["multicolor"])
        self.assertEqual(info["tool_indices"], [0])
        self.assertEqual(info["total_filament_used_g"], 4.25)
        self.assertNotIn("single_filament_start_compatible", info)
        self.assertEqual(info["filaments"], [{
            "paint_index": 0,
            "material_type": "PLA",
            "color_rgb": [138, 148, 158],
            "color_hex": "#8A949E",
            "filament_used_g": 4.25,
        }])

    def test_single_color_non_zero_paint_index_two(self):
        data = (
            b'; paint_info = [{"paint_index":2,"material_type":"PLA","paint_color":[255,0,0]}]\r\n'
            b"T2 ; select third filament\r\n"
            b"; filament used [g] = 0.00, 0.00, 3.10, 0.00\r\n"
            b"; total filament used [g] = 3.10\r\n"
        )
        info = inspect_gcode_filaments(data)
        self.assertTrue(info["paint_info_present"])
        self.assertEqual(info["filament_count"], 1)
        self.assertFalse(info["multicolor"])
        self.assertEqual(info["tool_indices"], [2])
        self.assertNotIn("single_filament_start_compatible", info)
        self.assertEqual(info["total_filament_used_g"], 3.10)
        self.assertEqual(info["filaments"][0]["paint_index"], 2)
        self.assertEqual(info["filaments"][0]["color_hex"], "#FF0000")
        self.assertEqual(info["filaments"][0]["filament_used_g"], 3.10)

    def test_multicolor_non_contiguous_mixed_materials_and_repeated_headers(self):
        header_paint = (
            b'; paint_info = [{"paint_index":3,"material_type":"PETG","paint_color":[0,0,255]},'
            b'{"paint_index":1,"material_type":"PLA","paint_color":[0,255,0]}]\n'
        )
        footer_paint = (
            b'; paint_info = [{"paint_index":1,"material_type":"PLA","paint_color":[0,255,0,255]},'
            b'{"paint_index":3,"material_type":"PETG","paint_color":[0,0,255]}]\n'
        )
        data = (
            header_paint
            + b"T3\nG1 X1 Y1\nT1\nG1 X2 Y2\nT3\n"
            + b"; filament used [g] = 0.00, 1.47, 0.00, 1.85\n"
            + b"; total filament used [g] = 3.32\n"
            + footer_paint
        )
        info = inspect_gcode_filaments(data)
        self.assertTrue(info["paint_info_present"])
        self.assertEqual(info["filament_count"], 2)
        self.assertTrue(info["multicolor"])
        self.assertEqual(info["tool_indices"], [1, 3])
        self.assertEqual(info["total_filament_used_g"], 3.32)
        self.assertNotIn("single_filament_start_compatible", info)
        self.assertEqual(info["filaments"], [
            {
                "paint_index": 1,
                "material_type": "PLA",
                "color_rgb": [0, 255, 0],
                "color_hex": "#00FF00",
                "filament_used_g": 1.47,
            },
            {
                "paint_index": 3,
                "material_type": "PETG",
                "color_rgb": [0, 0, 255],
                "color_hex": "#0000FF",
                "filament_used_g": 1.85,
            },
        ])

    def test_absent_paint_info_and_optional_weights(self):
        minimal = b"; generated by AnycubicSlicerNext 2.0.0.3\nG1 X1 Y2 E0.01\n"
        info = inspect_gcode_filaments(minimal)
        self.assertFalse(info["paint_info_present"])
        self.assertEqual(info["filaments"], [])
        self.assertEqual(info["filament_count"], 0)
        self.assertFalse(info["multicolor"])
        self.assertEqual(info["tool_indices"], [])
        self.assertIsNone(info["total_filament_used_g"])
        self.assertNotIn("single_filament_start_compatible", info)

        multi_tool_no_paint = minimal + b"T0\nT2\n; filament used [g] = invalid\n; total filament used [g] = nan\n"
        info_multi = inspect_gcode_filaments(multi_tool_no_paint)
        self.assertFalse(info_multi["paint_info_present"])
        self.assertTrue(info_multi["multicolor"])
        self.assertEqual(info_multi["tool_indices"], [0, 2])
        self.assertIsNone(info_multi["total_filament_used_g"])
        self.assertNotIn("single_filament_start_compatible", info_multi)

    def test_conflicting_and_malformed_paint_info_rejected(self):
        cases = (
            b"; paint_info = not-json\n",
            b"; paint_info = {}\n",
            b"; paint_info = []\n",
            b'; paint_info = ["bad"]\n',
            b'; paint_info = [{"paint_index":-1,"material_type":"PLA","paint_color":[0,0,0]}]\n',
            b'; paint_info = [{"paint_index":true,"material_type":"PLA","paint_color":[0,0,0]}]\n',
            b'; paint_info = [{"paint_index":0,"material_type":"PLA","paint_color":[0,0,0]},'
            b'{"paint_index":0,"material_type":"PETG","paint_color":[1,1,1]}]\n',
            b'; paint_info = [{"paint_index":0,"material_type":"","paint_color":[0,0,0]}]\n',
            b'; paint_info = [{"paint_index":0,"material_type":"PLA\\x00","paint_color":[0,0,0]}]\n',
            b'; paint_info = [{"paint_index":0,"material_type":"PLA","paint_color":[0,0,999]}]\n',
            (b'; paint_info = [{"paint_index":0,"material_type":"PLA","paint_color":[0,255,0]}]\n'
             b'; paint_info = [{"paint_index":0,"material_type":"PLA","paint_color":[255,0,0]}]\n'),
            (b'; paint_info = [{"paint_index":0,"material_type":"PLA","paint_color":[0,255,0]}]\n'
             b'; paint_info = [{"paint_index":0,"material_type":"PETG","paint_color":[0,255,0]}]\n'),
            (b'; paint_info = [{"paint_index":0,"material_type":"PLA","paint_color":[0,255,0]}]\n'
             b'; paint_info = [{"paint_index":1,"material_type":"PLA","paint_color":[0,255,0]}]\n'),
            b"; paint_info = " + b"[" * 2000 + b"]" * 2000 + b"\n",
        )
        for payload in cases:
            with self.subTest(payload=payload), self.assertRaises(ProtocolError):
                inspect_gcode_filaments(payload)


class ParseOnboardBoxTests(unittest.TestCase):
    def test_mixed_loaded_empty_and_other_slots_sorted_and_sanitized(self):
        boxes = [{
            "id": -1,
            "secret_url": "http://192.0.2.10/?token=SYNTHETIC",
            "slots": [
                {"index": 3, "status": 2, "type": "TPU", "color": [10, 20, 30]},
                {"index": 0, "status": 5, "type": "PLA High Speed", "color": [255, 255, 255, 255],
                 "raw_unknown": "drop-me"},
                {"index": 2, "status": 5, "type": "", "color": [10, 20, 30]},
                {"index": 1, "status": 0, "type": "", "color": []},
            ],
        }]
        result = parse_onboard_box(boxes)
        self.assertEqual(result["box_id"], -1)
        self.assertEqual(result["box_kind"], "onboard")
        self.assertEqual(result["slot_count"], 4)
        self.assertEqual(result["loaded_count"], 2)
        self.assertNotIn("secret_url", result)
        self.assertEqual(result["slots"], [
            {
                "slot": 1, "ams_index": 0, "status": 5, "status_label": "loaded",
                "available_for_start": True, "material_type": "PLA High Speed",
                "color_rgb": [255, 255, 255], "color_hex": "#FFFFFF",
            },
            {
                "slot": 2, "ams_index": 1, "status": 0, "status_label": "empty",
                "available_for_start": False, "material_type": None,
                "color_rgb": None, "color_hex": None,
            },
            {
                "slot": 3, "ams_index": 2, "status": 5, "status_label": "loaded",
                "available_for_start": False, "material_type": None,
                "color_rgb": [10, 20, 30], "color_hex": "#0A141E",
            },
            {
                "slot": 4, "ams_index": 3, "status": 2, "status_label": "other",
                "available_for_start": False, "material_type": "TPU",
                "color_rgb": [10, 20, 30], "color_hex": "#0A141E",
            },
        ])

    def test_loaded_slot_with_incomplete_color_or_url_material_is_not_start_available(self):
        boxes = [{
            "id": -1,
            "slots": [
                {"index": 0, "status": 5, "type": "PLA", "color": [999, 0, 0]},
                {"index": 1, "status": 5, "type": "https://example.test/?token=secret", "color": [0, 255, 0]},
                {"index": 2, "status": 0},
                {"index": 3, "status": 0, "type": None, "color": None},
            ],
        }]
        result = parse_onboard_box(boxes)
        self.assertFalse(result["slots"][0]["available_for_start"])
        self.assertIsNone(result["slots"][0]["color_rgb"])
        self.assertFalse(result["slots"][1]["available_for_start"])
        self.assertIsNone(result["slots"][1]["material_type"])
        self.assertEqual(result["slots"][2]["status_label"], "empty")
        self.assertIsNone(result["slots"][2]["color_hex"])

    def test_structural_and_external_box_violations_rejected(self):
        valid_slots = [{"index": i, "status": 0} for i in range(4)]
        cases = (
            None,
            [],
            [{"id": 0, "slots": valid_slots}],
            [{"id": True, "slots": valid_slots}],
            [{"id": -1, "slots": valid_slots}, {"id": 0, "slots": valid_slots}],
            [{"id": -1, "slots": valid_slots[:3]}],
            [{"id": -1, "slots": [{"index": 0, "status": 0}, {"index": 0, "status": 0},
                                  {"index": 2, "status": 0}, {"index": 3, "status": 0}]}],
            [{"id": -1, "slots": [{"index": i, "status": True} for i in range(4)]}],
            [{"id": -1, "slots": [{"index": i, "status": "5"} for i in range(4)]}],
            [{"id": -1, "slots": [{"index": 0, "status": 5, "type": "PLA", "color": "#FFFFFF"},
                                  *valid_slots[1:]]}],
            [{"id": -1, "slots": [{"index": 0, "status": 5, "type": 123, "color": [0, 0, 0]},
                                  *valid_slots[1:]]}],
        )
        for bad in cases:
            with self.subTest(bad=bad), self.assertRaises(ProtocolError):
                parse_onboard_box(bad)


class ListSlotsTests(unittest.TestCase):
    def make_client(self, info, box_data):
        calls = []

        class FakeClient:
            def __init__(self, cfg):
                self.cfg = cfg

            def __enter__(self):
                return self

            def __exit__(self, *args):
                pass

            def query(self, kind, action="query", data=None, *, require_fresh=False):
                calls.append((kind, action, require_fresh))
                if kind == "info":
                    return {"code": 200, "data": info}
                if (kind, action) == ("multiColorBox", "getInfo"):
                    return {"code": 200, "data": box_data}
                raise AssertionError(f"Unexpected query {(kind, action)}")

        return FakeClient, calls

    def test_succeeds_when_idle_or_busy_in_one_session(self):
        box_data = {
            "multi_color_box": [{
                "id": -1,
                "slots": [
                    {"index": 0, "status": 5, "type": "PLA High Speed", "color": [255, 255, 255]},
                    {"index": 1, "status": 5, "type": "PLA", "color": [0, 128, 255]},
                    {"index": 2, "status": 0, "type": "", "color": []},
                    {"index": 3, "status": 5, "type": "PETG", "color": [255, 0, 0]},
                ],
            }]
        }
        for info in (
            {"model": "Anycubic Kobra X", "version": "2.0.2.2", "state": "free", "project": None},
            {"model": "Anycubic Kobra X", "version": "2.0.2.2", "state": "busy",
             "project": {"state": "printing", "filename": "active.gcode"}},
        ):
            client_cls, calls = self.make_client(info, box_data)
            with self.subTest(state=info["state"]), patch("kobra_lan.filaments.MQTT", client_cls):
                result = list_slots(config())
            self.assertEqual(calls, [("info", "query", True), ("multiColorBox", "getInfo", False)])
            self.assertEqual(result["model"], "Anycubic Kobra X")
            self.assertEqual(result["firmware"], "2.0.2.2")
            self.assertEqual(result["printer_state"], info["state"])
            self.assertEqual(result["box_id"], -1)
            self.assertEqual(result["loaded_count"], 3)
            self.assertEqual([s["slot"] for s in result["slots"]], [1, 2, 3, 4])

    def test_unqualified_firmware_or_model_fails_before_box_query(self):
        for bad_info in (
            {"model": "Anycubic Kobra X", "version": "2.0.2.3", "state": "free"},
            {"model": "Other Printer", "version": "2.0.2.2", "state": "free"},
            {"model": "Anycubic Kobra X", "version": "2.0.2.2", "state": "free", "deviceId": "wrong"},
        ):
            client_cls, calls = self.make_client(bad_info, {})
            with self.subTest(bad_info=bad_info), patch("kobra_lan.filaments.MQTT", client_cls):
                with self.assertRaises(ProtocolError):
                    list_slots(config())
            self.assertEqual(calls, [("info", "query", True)])

    def test_network_tls_and_disconnect_failures_preserve_exit_classes(self):
        for error, expected_type in (
            (MQTTFailure("tls_pin", "pin_mismatch", "pin changed", 2), MQTTFailure),
            (MQTTFailure("status", "timeout", "timeout", 3), MQTTFailure),
            (MQTTIOFailure("status"), MQTTIOFailure),
            (MQTTClosed("status", "protocol_rejected", "closed"), ConnectionError),
        ):
            class FailingClient:
                def __init__(self, cfg):
                    pass

                def __enter__(self):
                    raise error

                def __exit__(self, *args):
                    pass

            with self.subTest(error=type(error).__name__), patch("kobra_lan.filaments.MQTT", FailingClient):
                with self.assertRaises(expected_type):
                    list_slots(config())


class SlotsCliTests(unittest.TestCase):
    def test_slots_help_and_bare_slots_refusal_need_no_registry(self):
        for argv in (["slots", "--help"], ["slots", "list", "--help"]):
            out = io.StringIO()
            with patch("kobra_lan.cli.Registry") as registry, contextlib.redirect_stdout(out):
                with self.assertRaises(SystemExit) as exited:
                    main(argv)
            self.assertEqual(exited.exception.code, 0)
            registry.assert_not_called()
            self.assertIn("onboard", out.getvalue().lower())

        for mode in ([], ["--json"]):
            out, err = io.StringIO(), io.StringIO()
            with patch("kobra_lan.cli.Registry") as registry, \
                    contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
                self.assertEqual(main([*mode, "slots"]), 2)
            registry.assert_not_called()
            self.assertEqual(err.getvalue(), "")
            if mode:
                report = json.loads(out.getvalue())
                self.assertEqual(report["schema_version"], 1)
                self.assertFalse(report["ok"])
                self.assertEqual(report["error"]["code"], "invalid_arguments")
            else:
                self.assertIn("slots --help", out.getvalue())

    def test_slots_list_text_and_json_parity_without_state_writes(self):
        class SyntheticClient:
            def __init__(self, cfg):
                pass

            def __enter__(self):
                return self

            def __exit__(self, *args):
                pass

            def query(self, kind, action="query", data=None, *, require_fresh=False):
                if kind == "info":
                    return {"code": 200, "data": {
                        "model": "Anycubic Kobra X", "version": "2.0.2.2", "state": "free",
                    }}
                return {"code": 200, "data": {"multi_color_box": [{
                    "id": -1,
                    "slots": [
                        {"index": 0, "status": 5, "type": "PLA High Speed", "color": [255, 255, 255]},
                        {"index": 1, "status": 0, "type": "", "color": []},
                        {"index": 2, "status": 5, "type": "PETG", "color": [0, 255, 0, 255]},
                        {"index": 3, "status": 2, "type": "ABS", "color": [12, 34, 56]},
                    ],
                }]}}

        with tempfile.TemporaryDirectory() as directory:
            state_dir = Path(directory) / "state"
            outputs = {}
            for mode_name, mode_flags in (("json", ["--json"]), ("text", [])):
                out, err = io.StringIO(), io.StringIO()
                with patch("kobra_lan.cli.Registry") as registry, \
                        patch("kobra_lan.filaments.MQTT", SyntheticClient), \
                        contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
                    registry.return_value.access.return_value.__enter__.return_value = (config(), {})
                    code = main([*mode_flags, "--printer", "bench", "--state-dir", str(state_dir), "slots", "list"])
                self.assertEqual(code, 0)
                self.assertEqual(err.getvalue(), "")
                registry.return_value.access.assert_called_once_with(None, "bench")
                outputs[mode_name] = out.getvalue()
            self.assertFalse(state_dir.exists())

        envelope = json.loads(outputs["json"])
        self.assertEqual(envelope["schema_version"], 1)
        self.assertTrue(envelope["ok"])
        result = envelope["result"]
        self.assertEqual(result["box_id"], -1)
        self.assertEqual(result["box_kind"], "onboard")
        self.assertEqual(result["slot_count"], 4)
        self.assertEqual(result["loaded_count"], 2)
        self.assertEqual([s["slot"] for s in result["slots"]], [1, 2, 3, 4])
        self.assertEqual(result["slots"][0]["color_hex"], "#FFFFFF")
        self.assertTrue(result["slots"][0]["available_for_start"])
        self.assertEqual(result["slots"][1]["status_label"], "empty")
        self.assertFalse(result["slots"][1]["available_for_start"])
        self.assertEqual(result["slots"][2]["color_hex"], "#00FF00")
        self.assertEqual(result["slots"][3]["status_label"], "other")
        self.assertFalse(result["slots"][3]["available_for_start"])

        text = outputs["text"]
        for expected in (
            "Box id: -1",
            "Box kind: onboard",
            "Slot count: 4",
            "Loaded count: 2",
            "PLA High Speed",
            "#FFFFFF",
            "Status label: empty",
            "PETG",
            "#00FF00",
            "Status label: other",
            "Available for start: yes",
            "Available for start: no",
            "Qualified:",
        ):
            self.assertIn(expected, text)

    def test_slots_list_exit_codes_for_validation_and_network_failures(self):
        cases = (
            (MQTTFailure("tls_pin", "pin_mismatch", "pin changed", 2), 2, "validation_failed"),
            (ProtocolError("Only the onboard four-slot configuration is supported"), 2, "validation_failed"),
            (MQTTFailure("status", "timeout", "MQTT timeout", 3), 3, "operation_failed"),
            (MQTTClosed("status", "protocol_rejected", "closed"), 3, "operation_failed"),
            (MQTTIOFailure("status"), 3, "operation_failed"),
        )
        for error, expected_exit, expected_code in cases:
            class FailingClient:
                def __init__(self, cfg):
                    pass

                def __enter__(self):
                    raise error

                def __exit__(self, *args):
                    pass

            out = io.StringIO()
            with self.subTest(error=type(error).__name__, expected_exit=expected_exit), \
                    patch("kobra_lan.cli.Registry") as registry, \
                    patch("kobra_lan.filaments.MQTT", FailingClient), \
                    contextlib.redirect_stdout(out):
                registry.return_value.access.return_value.__enter__.return_value = (config(), {})
                self.assertEqual(main(["--json", "slots", "list"]), expected_exit)
            report = json.loads(out.getvalue())
            self.assertFalse(report["ok"])
            self.assertEqual(report["error"]["code"], expected_code)


