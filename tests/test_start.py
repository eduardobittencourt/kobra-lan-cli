    def test_reprint_consumes_review_once_and_never_changes_upload_provenance(self):
        uploaded = self.receipt()
        provenance = uploaded.read_bytes()
        digest = self.plan()['plan_sha256']
        code, first = self.invoke_route('start', digest=digest, client=Active)
        self.assertEqual(code, 0)
        first = first['result']
        previous = first['attempt_id']
        code, plan = self.invoke_route('plan', previous=previous)
        self.assertEqual(code, 0)
        reprint_digest = plan['result']['plan_sha256']
        self.assertEqual(self.invoke_route('start', digest=digest, previous=previous, client=Active)[0], 2)
        self.assertEqual(self.invoke_route('start', digest=reprint_digest, previous=previous, slot=2)[0], 2)
        code, second = self.invoke_route('start', digest=reprint_digest, previous=previous, client=Active)
        self.assertEqual(code, 0)
        second = second['result']
        self.assertEqual(second['previous_attempt_id'], previous)
        self.assertNotEqual(second['attempt_id'], previous)
        self.assertEqual(second['status'], 'start_observed_active')
        self.assertEqual(self.invoke_route('plan', previous=previous)[0], 2)
        self.assertEqual(self.invoke_route('start', digest=reprint_digest, previous=previous)[0], 2)
        self.assertEqual(self.invoke_route('plan', previous=second['attempt_id'])[0], 0)
        code, text = self.invoke_route('plan', mode=False)
        self.assertEqual(code, 0)
        self.assertIn('Attempt id: ' + second['attempt_id'], text)
        self.assertEqual(Client.starts, 2)
        self.assertEqual(uploaded.read_bytes(), provenance)

