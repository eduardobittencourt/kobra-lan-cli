    def mapped_gcode(self, declarations):
        paint = [{"paint_index": index, "material_type": material, "paint_color": [index, 10, 20]}
                 for index, material in declarations]
        lines = [b"; paint_info = " + json.dumps(paint).encode()]
        lines.extend(f"T{index}".encode() for index, _ in declarations)
        data = b"\n".join(
            b"\n".join(lines) if line.startswith(b"; paint_info = ") else line
            for line in GCODE.split(b"\n")
        )
        self.file.write_bytes(data)
        client = MappedClient(config())
        client.file_size = len(data)
        return client

    def test_nonzero_contiguous_and_sparse_mappings(self):
        cases = (
            ([(2, "PLA")], {2: 2}, [(2, 1)], True),
            ([(1, "PLA"), (0, "PLA")], {1: 1, 0: 1}, [(0, 0), (1, 0)], True),
            ([(3, "PETG"), (1, "PLA")], {3: 4, 1: 2}, [(1, 1), (3, 3)], False),
        )
        for declarations, slot_map, pairs, expected_validated in cases:
            with self.subTest(declarations=declarations):
                client = self.mapped_gcode(declarations)
                args = (config(), client, self.file, "test.gcode")
                plan = build_plan(*args, slot_map, True, False, False)
                wire = plan["payload"]["ams_settings"]["ams_box_mapping"]
                self.assertEqual([(entry["paint_index"], entry["ams_index"]) for entry in wire], pairs)
                self.assertEqual([(entry["paint_index"], entry["slot"]) for entry in plan["slot_mapping"]],
                                 [(index, ams + 1) for index, ams in pairs])
                self.assertEqual(plan["multicolor"], len(pairs) > 1)
                self.assertEqual(plan["hardware_start_validated"], expected_validated)
                reordered = build_plan(*args, dict(reversed(list(slot_map.items()))), True, False, False)
                self.assertEqual(plan["plan_sha256"], reordered["plan_sha256"])
                if 4 in slot_map.values():
                    self.assertEqual(wire[-1]["ams_color"], [10, 20, 30, 40])
                    self.assertEqual(wire[-1]["material_type"], "PETG")
                    self.assertEqual(plan["slot_mapping"][-1]["slot_color_hex"], "#0A141E")

