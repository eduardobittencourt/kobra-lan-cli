import json
import tempfile
import unittest
from pathlib import Path
from unittest.mock import Mock, patch

from kobra_lan.config import ProtocolError
from kobra_lan.mqtt import MQTT, string
from kobra_lan.start import build_plan, start
from kobra_lan.upload import describe, atomic_json
from test_client import config

GCODE = (b'; generated by AnycubicSlicerNext 2.0.0.3\n; total layer number: 460\n'
         b'; paint_info = [{"paint_index":0,"material_type":"PLA","paint_color":[138,148,158]}]\n'
         b'G9111 bedTemp=60 extruderTemp=220\n; printer_model = Anycubic Kobra X\n')


class Client:
    material = "PLA High Speed"
    slot_status = 5
    starts = 0
    fail_start = False
    def __init__(self, cfg): pass
    def __enter__(self): return self
    def __exit__(self, *args): pass
    def query(self, kind, action="query", data=None):
        if kind == "info":
            d = {"model": "Anycubic Kobra X", "version": "2.0.2.2", "state": "free", "project": None}
        elif kind == "file":
            d = {"filename": "test.gcode", "file_details": {"file_size": len(GCODE),
                 "layer_count": 460, "printer_model": "Anycubic Kobra X"}}
        else:
            d = {"multi_color_box": [{"id": -1, "slots": [
                {"index": i, "status": self.slot_status, "type": self.material, "color": [255, 255, 255]}
                for i in range(4)]}]}
        return {"code": 200, "data": d}
    def start_once(self, payload):
        Client.starts += 1
        if self.fail_start: raise TimeoutError()
        return {"code": 0}


class StartTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.root = Path(self.tmp.name)
        self.file = self.root / "test.gcode"
        self.file.write_bytes(GCODE)
        Client.material = "PLA High Speed";Client.slot_status = 5;Client.starts = 0;Client.fail_start = False
    def tearDown(self): self.tmp.cleanup()
    def plan(self, slot=1):
        return build_plan(config(), Client(config()), self.file, "test.gcode", slot, True, False, False)
    def receipt(self):
        import hashlib
        _, d = describe(self.file, "test.gcode")
        device = hashlib.sha256(config().printer_id.encode()).hexdigest()[:16]
        p = self.root / "state" / device / (d["sha256"] + ".json")
        p.parent.mkdir(parents=True)
        atomic_json(p, {**d, "status": "uploaded_verified_by_listing_and_metadata"})
    def run_start(self, execute=False, expected=None):
        return start(config(), self.file, "test.gcode", 1, True, False, False,
                     self.root / "state", execute, expected)
    def test_dry_run_does_not_start_or_upload(self):
        with patch("kobra_lan.start.MQTT", Client):
            p = self.run_start()
        self.assertTrue(p["dry_run"])
        self.assertEqual(Client.starts, 0)
        self.assertFalse((self.root / "state").exists())
    def test_mapping_slot_and_explicit_settings(self):
        p = self.plan(slot=4)["payload"]
        self.assertEqual(p["ams_settings"]["ams_box_mapping"][0]["ams_index"], 3)
        self.assertEqual(p["ams_settings"]["ams_box_mapping"][0]["paint_index"], 0)
        self.assertEqual(p["task_settings"]["auto_leveling"], 1)
        self.assertEqual(p["task_settings"]["flow_calibration"], 0)
        self.assertEqual(p["url"], "")
    def test_hardware_qualification_is_limited_to_observed_case(self):
        self.assertTrue(self.plan(slot=1)["hardware_start_validated"])
        self.assertFalse(self.plan(slot=4)["hardware_start_validated"])
        p = build_plan(config(), Client(config()), self.file, "test.gcode", 1, True, True, False)
        self.assertFalse(p["hardware_start_validated"])
    def test_material_mismatch_blocks_plan(self):
        Client.material = "PETG"
        with self.assertRaises(ProtocolError): self.plan()
    def test_empty_slot_blocks_plan(self):
        Client.slot_status = 0
        with self.assertRaises(ProtocolError): self.plan()
    def test_multiple_tools_rejected(self):
        self.file.write_bytes(GCODE + b'T1\n')
        with self.assertRaises(ProtocolError): self.plan()
    def test_missing_or_changed_plan_blocks_execution(self):
        with patch("kobra_lan.start.MQTT", Client):
            with self.assertRaises(ProtocolError): self.run_start(True, "changed")
        self.assertEqual(Client.starts, 0)
    def test_verified_upload_receipt_required(self):
        p = self.plan()
        with patch("kobra_lan.start.MQTT", Client):
            with self.assertRaises(ProtocolError): self.run_start(True, p["plan_sha256"])
        self.assertEqual(Client.starts, 0)
    def test_timeout_cannot_replay_start(self):
        self.receipt();p = self.plan();Client.fail_start = True
        with patch("kobra_lan.start.MQTT", Client):
            with self.assertRaises(ProtocolError): self.run_start(True, p["plan_sha256"])
            with self.assertRaises(ProtocolError): self.run_start(True, p["plan_sha256"])
        self.assertEqual(Client.starts, 1)
    def test_ack_is_not_physical_start_confirmation(self):
        self.receipt();p = self.plan()
        with patch("kobra_lan.start.MQTT", Client), patch("kobra_lan.start.time.sleep"):
            result = self.run_start(True, p["plan_sha256"])
        self.assertEqual(result["status"], "start_acknowledged_not_confirmed")
        self.assertEqual(Client.starts, 1)
    def test_transport_publishes_once_on_timeout(self):
        m = MQTT(config());m.sock = Mock()
        with patch.object(m, "receive", side_effect=TimeoutError()):
            with self.assertRaises(TimeoutError):m.start_once({"filename": "test.gcode"})
        self.assertEqual(m.sock.sendall.call_count, 1)
    def test_transport_waits_for_correlated_ack(self):
        m = MQTT(config());m.sock = Mock()
        def response(deadline):
            raw = m.sock.sendall.call_args.args[0];d = json.loads(raw[raw.index(b'{'):])
            return 0x30, string("root/response") + json.dumps({"code": 0, "msgid": d["msgid"]}).encode()
        with patch.object(m, "receive", side_effect=response):
            self.assertEqual(m.start_once({"filename": "test.gcode"})["code"], 0)
        self.assertEqual(m.sock.sendall.call_count, 1)


if __name__ == "__main__": unittest.main()
