    def invoke_route(self, command, mode=True, digest=None, client=Client, previous=None, *, slot=1,
                     slot_map=None, selected=None, cfg=None, state_dir=None):
        import io
        from contextlib import redirect_stdout
        from kobra_lan.cli import main
        argv = ['--json'] if mode else []
        argv += ['--state-dir', str(state_dir or self.root/'state')]
        if selected is not None:
            argv += ['--printer', selected]
        argv += ['print', command, str(self.file),
                 '--name', 'test.gcode', '--auto-leveling', 'on',
                 '--vibration-compensation', 'off', '--flow-calibration', 'off']
        for index, mapped_slot in (slot_map if slot_map is not None else {0: slot}).items():
            argv += ['--slot-map', f'{index}={mapped_slot}']
        if previous is not None:
            argv += ['--reprint-from', previous]
        if command == 'start':
            argv += ['--execute', '--plan-sha256', digest]
        stdout = io.StringIO()
        with patch('kobra_lan.cli.Registry') as registry, patch('kobra_lan.start.MQTT', client), \
                patch('kobra_lan.start.time.sleep'), redirect_stdout(stdout):
            registry.return_value.access.return_value.__enter__.return_value = (cfg or config(), {})
            code = main(argv)
        return code, json.loads(stdout.getvalue()) if mode else stdout.getvalue()

