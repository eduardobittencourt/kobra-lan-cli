        self.assertEqual(self.invoke_route('start', digest=digest, previous=previous, client=BusyOnFinalCheck)[0], 2)
        self.assertEqual(list(marker.parent.glob('*.attempt')), [marker])
        self.assertEqual(Client.starts, 0)

