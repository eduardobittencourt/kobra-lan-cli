    def test_state_path_replacement_before_or_after_reservation_never_publishes(self):
        marker, _, previous, digest = self.canonical_reprint()
        directory = marker.parent
        detached = directory.with_name('detached')

        def swap():
            directory.rename(detached)
            directory.mkdir(mode=0o700)

        class ReplaceBefore(Client):
            info_calls = 0

            def query(self, kind, action='query', data=None, *, require_fresh=False):
                if kind == 'info':
                    self.info_calls += 1
                    if self.info_calls == 2:
                        swap()
                return super().query(kind, action, data, require_fresh=require_fresh)

        self.assertEqual(self.invoke_route('start', digest=digest, previous=previous, client=ReplaceBefore)[0], 2)
        self.assertEqual(len(list(detached.glob('*.attempt'))), 1)
        self.assertFalse(list(directory.iterdir()))
        directory.rmdir()
        detached.rename(directory)

        def reserve_then_swap(*args, **kwargs):
            reserve_at(*args, **kwargs)
            swap()

        with patch('kobra_lan.start.reserve_at', side_effect=reserve_then_swap):
            code, report = self.invoke_route('start', digest=digest, previous=previous)
        self.assertEqual(code, 2)
        self.assertEqual(len(list(detached.glob('*.attempt'))), 2)
        self.assertFalse(list(directory.iterdir()))
        self.assertEqual(report['result']['status'], 'start_uncertain_no_retry')
        self.assertEqual(Client.starts, 0)

