    def test_unfinished_successor_is_not_replayed_after_interruption(self):
        marker, receipt, previous, digest = self.legacy_reprint()
        original = marker.read_bytes(), receipt.read_bytes()
        with patch('kobra_lan.start.atomic_json', side_effect=KeyboardInterrupt):
            with self.assertRaises(KeyboardInterrupt):
                self.invoke_route('start', digest=digest, previous=previous)
        latest = self.invoke_route('plan')[1]['result']['attempt_id']
        self.assertNotEqual(latest, previous)
        successor = marker.parent/(latest + '.attempt')
        self.assertEqual(json.loads(successor.read_text())['previous_attempt_id'], previous)
        self.assertEqual(stat.S_IMODE(successor.stat().st_mode), 0o600)
        self.assertFalse(successor.with_suffix('.json').exists())
        self.assertEqual(self.invoke_route('start', digest=digest, previous=previous)[0], 2)
        self.assertEqual(self.invoke_route('plan', previous=latest)[0], 2)
        self.assertEqual(original, (marker.read_bytes(), receipt.read_bytes()))
        self.assertEqual(Client.starts, 0)

