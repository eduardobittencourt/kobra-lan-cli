"""Installed profile/doctor acceptance, synthetic home and transports only."""
import argparse
from contextlib import redirect_stdout, redirect_stderr
import io
import hashlib
import json
import os
from pathlib import Path
import runpy
import sys
import tempfile
from unittest.mock import MagicMock, patch


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--command', type=Path, required=True)
    args = parser.parse_args()
    import kobra_lan
    from kobra_lan.mqtt import MQTTFailure
    from kobra_lan.pairing import QUALIFIED_FIRMWARE
    from kobra_lan.provisioning import Bundle
    assert {'site-packages','dist-packages'} & set(Path(kobra_lan.__file__).resolve().parts)
    pin = 'a'*64
    duplicate_message = 'Upload already attempted; no network write was repeated'
    bundle = Bundle('Synthetic01',20030,'synthetic-user','synthetic-password','synthetic cert','synthetic key')

    class ReadOnly:
        fail_pin = False
        report_changes = {}
        def __init__(self, config, timeout=12, deadline=None, observer=None):
            self.observer = observer
        def __enter__(self):
            if self.fail_pin:
                raise MQTTFailure('tls_pin','pin_mismatch','synthetic failure')
            if self.observer:
                self.observer('tls_pin'); self.observer('mqtt_auth')
            return self
        def __exit__(self,*args): pass
        def query(self,kind):
            assert kind=='info'
            # Qualified firmware may omit optional numeric model/device IDs.
            return {'code':200,'data':{'model':'Anycubic Kobra X','version':QUALIFIED_FIRMWARE,'state':'printing',
                                     **self.report_changes}}

    def invoke(argv, expected=0):
        stdout, stderr = io.StringIO(), io.StringIO()
        with patch.object(sys,'argv',[str(args.command),"--json",*argv]), redirect_stdout(stdout), redirect_stderr(stderr):
            try:
                runpy.run_path(str(args.command),run_name='__main__')
            except SystemExit as exit:
                assert exit.code==expected, (exit.code,stdout.getvalue())
        assert not stderr.getvalue(), stderr.getvalue()
        assert 'synthetic-password' not in stdout.getvalue()
        return json.loads(stdout.getvalue())

    with tempfile.TemporaryDirectory(prefix='profiles-probe-',dir=Path.cwd()) as temporary:
        home=Path(temporary)
        with patch.dict(os.environ,{'HOME':str(home)}), \
                patch('socket.create_connection',side_effect=AssertionError('No real sockets')), \
                patch('kobra_lan.pairing.provision',return_value=bundle), \
                patch('kobra_lan.pairing.observe_fingerprint',return_value=pin), \
                patch('kobra_lan.pairing.MQTT',ReadOnly):
            assert invoke(['printer','list'])['result']['profiles']==[]
            invoke(['printer','pair','--name','first','--default','--host','192.0.2.10','--trust-sha256',pin])
            # Existing device markers must still block named access.
            gcode=home/'synthetic.gcode'
            gcode.write_bytes(b'; generated by AnycubicSlicerNext 2.0.0.3\n; total layer number: 1\n; printer_model = Anycubic Kobra X\n')
            sha=hashlib.sha256(gcode.read_bytes()).hexdigest()
            device=hashlib.sha256(b'Synthetic01').hexdigest()[:16]
            state=home/'.local/share/kobra-lan/uploads'
            directory=state/device; directory.mkdir(parents=True)
            marker=directory/(sha+'.attempt'); marker.write_bytes(b'synthetic uncertain upload')
            upload=['files','upload',str(gcode),'--execute','--sha256',sha]
            assert invoke(upload,expected=2)['error']['message']==duplicate_message
            invoke(['printer','pair','--name','bancada','--host','192.0.2.10','--trust-sha256',pin])
            assert invoke(['printer','list'])['result']['default']=={'name':'first'}
            assert invoke(['--printer','bancada',*upload],expected=2)['error']['message']==duplicate_message
            invoke(['printer','use','bancada'])
            assert invoke(['printer','info'])['result']['name']=='bancada'
            root=home/'.config/kobra-lan'
            before={str(p):(p.read_bytes(),p.stat().st_mode) for p in root.rglob('*') if p.is_file()}
            with patch('kobra_lan.diagnostics.MQTT',ReadOnly), \
                    patch('kobra_lan.diagnostics.socket.create_connection',return_value=MagicMock()) as tcp:
                assert invoke(['doctor'])['result']['healthy']
                ReadOnly.fail_pin=True
                failed=invoke(['doctor'],expected=2)
                assert failed['result']['checks'][4]['code']=='pin_mismatch'
                ReadOnly.fail_pin=False
                for changes, reason in (({'version': None}, 'qualification_incomplete'),
                                        ({'deviceId': 'Other01'}, 'outside_qualification')):
                    ReadOnly.report_changes = changes
                    failed = invoke(['doctor'], expected=2)
                    assert failed['result']['checks'][-2]['status'] == 'passed'
                    assert failed['result']['checks'][-1]['code'] == reason
                ReadOnly.report_changes = {}
                assert tcp.call_count==8
                assert all(c.kwargs['timeout']<=12 for c in tcp.call_args_list)
            assert before=={str(p):(p.read_bytes(),p.stat().st_mode) for p in root.rglob('*') if p.is_file()}
            invoke(['printer','remove','first','--yes'])
            removed=invoke(['printer','remove','bancada','--yes'])['result']
            assert removed['registration_removed'] and not removed['preserved_files']
            invoke(['status'],expected=2)
            assert marker.read_bytes()==b'synthetic uncertain upload'
            invoke(['printer','pair','--name','bancada','--host','192.0.2.10','--trust-sha256',pin])
            assert invoke(['printer','list'])['result']['default'] is None
            assert invoke(['--printer','bancada',*upload],expected=2)['error']['message']==duplicate_message
            assert marker.read_bytes()==b'synthetic uncertain upload'
            assert invoke(['--config',str(root/'profiles/bancada/config.json'),'printer','info'])['result']['source']=='profile'
            missing=invoke(['--config',str(home/'missing.json'),'doctor'],expected=3)
            assert missing['result']['checks'][0]['status']=='failed'
    print('Installed profiles and healthy/failed doctor verified; no printer access')


if __name__=='__main__':
    main()
