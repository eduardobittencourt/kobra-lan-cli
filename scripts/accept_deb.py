"""Destructive package lifecycle test: ONLY inside a disposable, networkless system.

Provision python3, passwd and util-linux beforehand. Run with PYTHONPATH unset.
The same immutable .deb must be passed to both supported distribution runs.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import pwd
import socket
import stat
import subprocess


def run(*args, **kwargs):
    return subprocess.run(args, check=True, **kwargs)


def snapshot(home):
    result = {}
    for base in (home / ".config/kobra-lan", home / ".local/share/kobra-lan"):
        for path in [base] + sorted(base.rglob("*")):
            s = path.stat()
            result[str(path.relative_to(home))] = (stat.S_IMODE(s.st_mode), s.st_uid, s.st_gid,
                                                   path.read_bytes() if path.is_file() else None)
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("deb", type=Path)
    parser.add_argument("version")
    parser.add_argument("--report", type=Path)
    args = parser.parse_args()
    assert os.geteuid() == 0
    assert Path("/run/kobra-package-acceptance").read_text().strip() == "disposable"
    os_release = dict(line.split("=", 1) for line in Path("/etc/os-release").read_text().splitlines() if "=" in line)
    assert (os_release["ID"].strip('"'), os_release["VERSION_ID"].strip('"')) in {("debian", "13"), ("ubuntu", "24.04")}
    # Provisioning is over: fail unless the caller isolated every non-loopback interface.
    assert {name for _, name in socket.if_nameindex()} <= {"lo"}, "Run in a network namespace or Docker --network none"
    deb = args.deb.resolve()
    original_hash = hashlib.sha256(deb.read_bytes()).hexdigest()
    work = Path("/var/lib/kobra-package-acceptance")
    work.mkdir()
    work.chmod(0o755)
    run("useradd", "--create-home", "--shell", "/bin/sh", "kobra-acceptance")
    account = pwd.getpwnam("kobra-acceptance")
    home = Path(account.pw_dir)
    directories = [".config/kobra-lan", ".local/share/kobra-lan/uploads/device",
                   ".local/share/kobra-lan/uploads/starts/device"]
    for name in directories:
        path = home / name
        path.mkdir(parents=True, exist_ok=True)
    fixtures = {
        ".config/kobra-lan/config.json": b'{"synthetic": true}\n',
        ".config/kobra-lan/client.key": b"SYNTHETIC-NON-KEY\n",
        ".local/share/kobra-lan/uploads/device/file.json": b'{"status":"uploaded_verified_by_listing_and_metadata"}\n',
        ".local/share/kobra-lan/uploads/starts/device/file.json": b'{"status":"start_uncertain_no_retry"}\n',
        ".local/share/kobra-lan/uploads/device/file.attempt": b"synthetic-reservation\x00\xff\n",
    }
    for name, data in fixtures.items():
        (home / name).write_bytes(data)
    for path in [home] + list(home.rglob("*")):
        os.chown(path, account.pw_uid, account.pw_gid)
        path.chmod(0o700 if path.is_dir() else 0o600)
    before = snapshot(home)
    fixture = work / "old"
    (fixture / "DEBIAN").mkdir(parents=True)
    (fixture / "DEBIAN/control").write_text(
        "Package: kobra-lan-cli\nVersion: 0.0.0~fixture-1\nArchitecture: all\n"
        "Maintainer: Test Fixture <fixture@example.invalid>\nDescription: synthetic older package\n")
    (fixture / "usr/bin").mkdir(parents=True)
    (fixture / "usr/bin/kobra-lan").write_text("#!/bin/sh\necho synthetic-older-fixture\n")
    (fixture / "usr/bin/kobra-lan").chmod(0o755)
    old = work / "older.deb"
    run("dpkg-deb", "--build", "--root-owner-group", str(fixture), str(old))

    def apt(*arguments):
        # APT's --no-download mishandles local .deb acquisition on both targets.
        # The empty network namespace enforces offline installation instead.
        run("apt-get", "-y", *arguments, env=dict(os.environ, DEBIAN_FRONTEND="noninteractive"))
        assert snapshot(home) == before, f"Private data changed after {arguments}"

    def probe(*arguments, code=0):
        # Explicit installed path, empty environment, no checkout, development launcher or PYTHONPATH.
        result = subprocess.run(["runuser", "-u", "kobra-acceptance", "--", "env", "-i",
                                 f"HOME={home}", "PATH=/usr/bin:/bin", "/usr/bin/kobra-lan", *arguments],
                                cwd=work, text=True, capture_output=True)
        assert result.returncode == code, (arguments, result.returncode, result.stdout, result.stderr)
        return result.stdout

    def installed_probes():
        assert probe("--version").strip() == args.version
        assert "usage:" in probe("--help")
        gcode = work / "synthetic.gcode"
        gcode.write_bytes(b'; generated by AnycubicSlicerNext 2.0.0.3\n; total layer number: 1\n'
                          b'G1 X1 Y2 E0.01\n; printer_model = Anycubic Kobra X\n')
        gcode.chmod(0o644)
        result = json.loads(probe("inspect", str(gcode)))
        assert result["ok"] and result["result"]["layer_count"] == 1
        assert result["result"]["sha256"] == hashlib.sha256(gcode.read_bytes()).hexdigest()
        assert result["result"]["starts_print"] is False
        result = json.loads(probe("--config", str(home / "missing.json"), "status", code=3))
        assert result == {"ok": False, "error": "Local configuration or network operation failed; no automatic retry"}
        assert snapshot(home) == before

    # Clean installation, then a controlled old package -> tested candidate upgrade.
    apt("install", str(deb))
    installed_probes()
    apt("remove", "kobra-lan-cli")
    apt("install", str(old))
    apt("install", str(deb))
    installed_probes()
    apt("remove", "kobra-lan-cli")
    assert not Path("/usr/bin/kobra-lan").exists()
    # No system conffiles remain after removal, so APT forgets this local-only
    # package. Reinstall before exercising purge as a separate lifecycle path.
    apt("install", str(deb))
    apt("purge", "kobra-lan-cli")
    assert not Path("/usr/bin/kobra-lan").exists()
    assert hashlib.sha256(deb.read_bytes()).hexdigest() == original_hash
    if args.report:
        args.report.write_text(json.dumps({"distribution": os_release["ID"].strip('"') + ":" + os_release["VERSION_ID"].strip('"'),
                                           "version": args.version, "sha256": original_hash, "passed": True}) + "\n")
    print(f"Acceptance + clean install/upgrade/remove/purge passed: {os_release['ID']} {os_release['VERSION_ID']}; sha256={original_hash}")


if __name__ == "__main__":
    main()
