"""Destructive package lifecycle test: ONLY inside a disposable, networkless system.

Provision python3, python3-cryptography (and its closure), passwd and util-linux
beforehand. Run with PYTHONPATH unset.
The same immutable .deb must be passed to both supported distribution runs.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import pwd
import socket
import stat
import subprocess

from probe_completions import check_completion


INSTALLED_COMMAND = "/usr/bin/kobra-lan"
CLEAN_PATH = "PATH=/usr/bin:/bin"


def run(*args, **kwargs):
    """Run an acceptance command once and fail on a nonzero exit."""
    return subprocess.run(args, check=True, **kwargs)


def snapshot(home):
    """Capture synthetic private-state bytes, ownership and modes for lifecycle comparison."""
    result = {}
    for base in (home / ".config/kobra-lan", home / ".local/share/kobra-lan"):
        for path in [base] + sorted(base.rglob("*")):
            s = path.stat()
            result[str(path.relative_to(home))] = (stat.S_IMODE(s.st_mode), s.st_uid, s.st_gid,
                                                   path.read_bytes() if path.is_file() else None)
    return result


def installed_probes(probe, version, home, work, before):
    """Check installed help, local inspection and synthetic pairing without printer access."""
    assert probe("--version").strip() == version
    assert "usage:" in probe("--help")
    assert "--trust-sha256" in probe("printer", "pair", "--help")
    result = json.loads(probe("--json", "printer", "pair", "--name", "bancada", "--host", "192.0.2.10", code=2))
    assert not result["ok"] and "already registered" in result["error"]["message"]
    result = json.loads(probe("--json", "printer", "pair", "--name", "invalidhost", "--host", "invalid", code=2))
    assert not result["ok"] and "Identity:" in result["error"]["message"]
    # Invoke the installed entry point with synthetic transports in its own Python.
    run("runuser", "-u", "kobra-acceptance", "--", "env", "-i", f"HOME={home}",
        CLEAN_PATH, "/usr/bin/python3", "/probe_pairing.py", "--command", INSTALLED_COMMAND, cwd=home)
    assert "doctor" in probe("--help")
    assert "--yes" in probe("printer", "remove", "--help")
    run("runuser", "-u", "kobra-acceptance", "--", "env", "-i", f"HOME={home}",
        CLEAN_PATH, "/usr/bin/python3", "/probe_profiles.py", "--command", INSTALLED_COMMAND, cwd=home)
    gcode = work / "synthetic.gcode"
    gcode.write_bytes(b'; generated by AnycubicSlicerNext 2.0.0.3\n; total layer number: 1\n'
                      b'G1 X1 Y2 E0.01\n; printer_model = Anycubic Kobra X\n')
    gcode.chmod(0o644)
    result = json.loads(probe("--json", "gcode", "inspect", str(gcode)))
    assert result["ok"] and result["result"]["layer_count"] == 1
    assert result["result"]["sha256"] == hashlib.sha256(gcode.read_bytes()).hexdigest()
    assert result["result"]["starts_print"] is False
    result = json.loads(probe("--json", "--config", str(home / "missing.json"), "status", code=3))
    assert result["schema_version"] == 1 and result["error"]["code"] == "operation_failed"
    assert "Sha256:" in probe("gcode", "inspect", str(gcode))
    empty_home = work / "empty-home"
    empty_home.mkdir(exist_ok=True)
    home_owner = home.stat()
    os.chown(empty_home, home_owner.st_uid, home_owner.st_gid)
    assert "discover" in probe("printer", "--help", probe_home=empty_home)
    discover_help = probe("printer", "discover", "--help", probe_home=empty_home)
    assert all(flag in discover_help for flag in ("--timeout", "--interface", "ac:3dprinter:fdm"))
    hostile = "https://example.test/?token=SYNTHETIC_PRIVATE"
    for mode in ([], ["--json"]):
        output = probe(*mode, "printer", "discover", "--interface", hostile, code=2,
                       probe_home=empty_home, quiet_stderr=True)
        assert "SYNTHETIC_PRIVATE" not in output
        if mode:
            assert json.loads(output)["error"]["code"] == "invalid_arguments"
    slots_help = probe("slots", "--help", probe_home=empty_home)
    assert "list" in slots_help
    assert "onboard" in probe("slots", "list", "--help", probe_home=empty_home).lower()
    camera_help = probe("camera", "--help", probe_home=empty_home)
    assert all(word in camera_help for word in ("status", "snapshot", "pipe"))
    assert "18088" in probe("camera", "status", "--help", probe_home=empty_home)
    camera_snap_help = probe("camera", "snapshot", "--help", probe_home=empty_home)
    assert all(flag in camera_snap_help for flag in ("--output", "--timeout", "--overwrite", "--no-start-capture"))
    camera_pipe_help = probe("camera", "pipe", "--help", probe_home=empty_home)
    assert all(flag in camera_pipe_help for flag in ("--timeout", "--max-bytes", "--no-start-capture"))
    pipe_json = json.loads(probe("--json", "camera", "pipe", code=2, probe_home=empty_home, quiet_stderr=True))
    assert pipe_json["error"]["code"] == "invalid_arguments"
    assert "delete" in probe("files", "--help", probe_home=empty_home)
    delete_help = probe("files", "delete", "--help", probe_home=empty_home)
    assert "--execute" in delete_help and "idle printer" in " ".join(delete_help.split())
    hostile = "https://example.test/?token=SYNTHETIC_PRIVATE"
    for mode in ([], ["--json"]):
        output = probe(*mode, "files", "delete", hostile, code=2, probe_home=empty_home)
        assert "SYNTHETIC_PRIVATE" not in output
        assert "files list" in output and "--execute" in output
        if mode:
            assert json.loads(output)["error"]["code"] == "invalid_arguments"
    print_help = probe("print", "--help", probe_home=empty_home)
    assert all(word in print_help for word in ("watch", "pause", "resume", "cancel"))
    assert "--timeout SECONDS" in probe("print", "watch", "--help", probe_home=empty_home)
    for action in ("plan", "start"):
        help_text = probe("print", action, "--help", probe_home=empty_home)
        assert "--reprint-from PREVIOUS_ATTEMPT_ID" in help_text
        assert "--slot-map PAINT_INDEX=SLOT" in help_text and "--slot" not in help_text.split()
        execution = ["--execute", "--plan-sha256", "a" * 64] if action == "start" else []
        for mode in ([], ["--json"]):
            output = probe(*mode, "print", action, str(gcode), "--name", "synthetic.gcode",
                           "--slot-map", hostile, "--auto-leveling", "on",
                           "--vibration-compensation", "off", "--flow-calibration", "off", *execution,
                           code=2, probe_home=empty_home, quiet_stderr=True)
            assert "SYNTHETIC_PRIVATE" not in output and "--slot-map" in output
            if mode:
                assert json.loads(output)["error"]["code"] == "invalid_arguments"
            else:
                assert output.count("Error (invalid_arguments):") == 1
    for action in ("pause", "resume", "cancel"):
        help_text = probe("print", action, "--help", probe_home=empty_home)
        assert "--execute" in help_text and "--filename" in help_text
    jobs_help = probe("jobs", "--help", probe_home=empty_home)
    assert "list" in jobs_help and "info" in jobs_help
    jobs_list_help = probe("jobs", "list", "--help", probe_home=empty_home)
    assert "--kind" in jobs_list_help and "--limit" in jobs_list_help
    assert "RECORD_ID" in probe("jobs", "info", "--help", probe_home=empty_home)
    for shell in ("bash", "zsh", "fish"):
        completion = probe("completion", shell, probe_home=empty_home)
        check_completion(completion, shell)
    assert not list(empty_home.iterdir())
    for mode in ([], ["--json"]):
        output = probe(*mode, "files", "upload", hostile, code=2)
        assert "SYNTHETIC_PRIVATE" not in output
        if mode:
            assert json.loads(output)["error"]["code"] == "invalid_arguments"
    for mode in ([], ["--json"]):
        output = probe(*mode, "printer", "pair", "--host", "192.0.2.10", code=2)
        if mode:
            assert json.loads(output)["error"]["code"] == "invalid_arguments"
    assert snapshot(home) == before


def main():
    """Exercise install, upgrade, remove and purge only in a disposable networkless system."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("deb", type=Path)
    parser.add_argument("version")
    parser.add_argument("--report", type=Path)
    args = parser.parse_args()
    assert os.geteuid() == 0
    assert Path("/run/kobra-package-acceptance").read_text().strip() == "disposable"
    os_release = dict(line.split("=", 1) for line in Path("/etc/os-release").read_text().splitlines() if "=" in line)
    assert (os_release["ID"].strip('"'), os_release["VERSION_ID"].strip('"')) in {("debian", "13"), ("ubuntu", "24.04")}
    # Provisioning is over: fail unless the caller isolated every non-loopback interface.
    assert {name for _, name in socket.if_nameindex()} <= {"lo"}, "Run in a network namespace or Docker --network none"
    deb = args.deb.resolve()
    original_hash = hashlib.sha256(deb.read_bytes()).hexdigest()
    work = Path("/var/lib/kobra-package-acceptance")
    work.mkdir()
    work.chmod(0o755)
    run("useradd", "--create-home", "--shell", "/bin/sh", "kobra-acceptance")
    account = pwd.getpwnam("kobra-acceptance")
    home = Path(account.pw_dir)
    directories = [".config/kobra-lan/profiles/bancada/.pair-" + "a" * 32, ".local/share/kobra-lan/uploads/device",
                   ".local/share/kobra-lan/uploads/starts/device"]
    for name in directories:
        path = home / name
        path.mkdir(parents=True, exist_ok=True)
    fixtures = {
        ".config/kobra-lan/profiles.json": json.dumps({"version": 1, "default": None, "profiles": {
            "bancada": {"config_path": str(home / ".config/kobra-lan/profiles/bancada/config.json"),
                        "firmware": "2.0.2.2", "owned_files": ["config.json", ".pair-" + "a" * 32 + "/client.key"]}}}).encode(),
        ".config/kobra-lan/profiles/bancada/config.json": b'{"synthetic_managed":true}\n',
        ".config/kobra-lan/profiles/bancada/.pair-" + "a" * 32 + "/client.key": b"SYNTHETIC-MANAGED-KEY\n",
        ".config/kobra-lan/.profiles.lock": b"",
        ".local/share/kobra-lan/uploads/device/file.json": b'{"status":"uploaded_verified_by_listing_and_metadata"}\n',
        ".local/share/kobra-lan/uploads/starts/device/file.json": b'{"status":"start_uncertain_no_retry"}\n',
        ".local/share/kobra-lan/uploads/device/file.attempt": b"synthetic-reservation\x00\xff\n",
    }
    for name, data in fixtures.items():
        (home / name).write_bytes(data)
    for path in [home] + list(home.rglob("*")):
        os.chown(path, account.pw_uid, account.pw_gid)
        path.chmod(0o700 if path.is_dir() else 0o600)
    before = snapshot(home)
    fixture = work / "old"
    (fixture / "DEBIAN").mkdir(parents=True)
    (fixture / "DEBIAN/control").write_text(
        "Package: kobra-lan-cli\nVersion: 0.0.0~fixture-1\nArchitecture: all\n"
        "Maintainer: Test Fixture <fixture@example.invalid>\nDescription: synthetic older package\n")
    (fixture / "usr/bin").mkdir(parents=True)
    (fixture / "usr/bin/kobra-lan").write_text("#!/bin/sh\necho synthetic-older-fixture\n")
    (fixture / "usr/bin/kobra-lan").chmod(0o755)
    old = work / "older.deb"
    run("dpkg-deb", "--build", "--root-owner-group", str(fixture), str(old))

    def apt(*arguments):
        # APT's --no-download mishandles local .deb acquisition on both targets.
        # The empty network namespace enforces offline installation instead.
        """Apply one package lifecycle operation and verify private fixtures are unchanged."""
        run("apt-get", "-y", *arguments, env=dict(os.environ, DEBIAN_FRONTEND="noninteractive"))
        assert snapshot(home) == before, f"Private data changed after {arguments}"

    def probe(*arguments, code=0, probe_home=home, quiet_stderr=False):
        # Explicit installed path, empty environment, no checkout, development launcher or PYTHONPATH.
        """Run the installed command as the fixture user outside the checkout."""
        result = subprocess.run(["runuser", "-u", "kobra-acceptance", "--", "env", "-i",
                                 f"HOME={probe_home}", CLEAN_PATH, INSTALLED_COMMAND, *arguments],
                                cwd=work, text=True, capture_output=True)
        assert result.returncode == code, (arguments, result.returncode, result.stdout, result.stderr)
        if quiet_stderr:
            assert not result.stderr
        return result.stdout

    # Clean installation, then a controlled old package -> tested candidate upgrade.
    apt("install", str(deb))
    installed_probes(probe, args.version, home, work, before)
    apt("remove", "kobra-lan-cli")
    apt("install", str(old))
    apt("install", str(deb))
    installed_probes(probe, args.version, home, work, before)
    apt("remove", "kobra-lan-cli")
    assert not Path(INSTALLED_COMMAND).exists()
    # No system conffiles remain after removal, so APT forgets this local-only
    # package. Reinstall before exercising purge as a separate lifecycle path.
    apt("install", str(deb))
    apt("purge", "kobra-lan-cli")
    assert not Path(INSTALLED_COMMAND).exists()
    assert hashlib.sha256(deb.read_bytes()).hexdigest() == original_hash
    if args.report:
        args.report.write_text(json.dumps({"distribution": os_release["ID"].strip('"') + ":" + os_release["VERSION_ID"].strip('"'),
                                           "version": args.version, "sha256": original_hash, "passed": True}) + "\n")
    print(f"Acceptance + clean install/upgrade/remove/purge passed: {os_release['ID']} {os_release['VERSION_ID']}; sha256={original_hash}")


if __name__ == "__main__":
    main()
