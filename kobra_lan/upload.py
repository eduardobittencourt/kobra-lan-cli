"""Immutable payload upload, separate from print/start, without automatic retries."""
import hashlib
import http.client
import json
import os
import re
import time
import uuid
from pathlib import Path
from urllib.parse import urlsplit

from .config import ProtocolError
from .mqtt import MQTT
from .printer import payload_data, sanitized, file_details, safe_file_details, list_files

MAX_FILE = 128 * 1024 * 1024


def atomic_json(path, data):
    tmp = path.with_name(path.name + "." + uuid.uuid4().hex + ".tmp")
    fd = os.open(tmp, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o600)
    try:
        with os.fdopen(fd, "w") as stream:
            json.dump(data, stream, indent=2)
            stream.write("\n")
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(tmp, path)
        directory = os.open(path.parent, os.O_RDONLY | os.O_DIRECTORY)
        try:
            os.fsync(directory)
        finally:
            os.close(directory)
    finally:
        tmp.unlink(missing_ok=True)


def describe(path, remote_name=None):
    path = Path(path)
    if path.suffix.lower() != ".gcode":
        raise ProtocolError("Only plain .gcode is qualified")
    if not 0 < path.stat().st_size <= MAX_FILE:
        raise ProtocolError("G-code is empty or exceeds the 128 MiB limit")
    data = path.read_bytes()
    sha = hashlib.sha256(data).hexdigest()
    name = remote_name or f"agent-{path.stem[:40]}-{sha[:12]}.gcode"
    if not re.fullmatch(r"[A-Za-z0-9_.-]{1,100}\.gcode", name):
        raise ProtocolError("Remote name must be a safe ASCII .gcode basename")
    header = data[:1500].decode("utf-8", errors="replace")
    match = re.search(r"generated by AnycubicSlicerNext ([\d.]+)", header)
    if not match:
        raise ProtocolError("Expected G-code generated by official Anycubic Slicer Next")
    if b"; printer_model = Anycubic Kobra X" not in data:
        raise ProtocolError("G-code does not declare a Kobra X profile")
    layers = re.search(rb"; total layer number: (\d+)", data[:1500])
    return data, {"sha256": sha, "md5": hashlib.md5(data).hexdigest(),
                  "size_bytes": len(data), "remote_filename": name,
                  "layer_count": int(layers.group(1)) if layers else None,
                  "slicer_version": match.group(1), "operation": "upload_only", "starts_print": False}


def multipart(data, name, boundary):
    sep = f"--{boundary}\r\n".encode()
    return (sep + b'Content-Disposition: form-data; name="filename"\r\n\r\n' + name.encode() + b"\r\n"
            + sep + f'Content-Disposition: form-data; name="gcode"; filename="{name}"\r\n'.encode()
            + b"Content-Type: application/octet-stream\r\n\r\n" + data
            + f"\r\n--{boundary}--\r\n".encode())


def upload_target(config, url):
    p = urlsplit(url)
    if (p.scheme != "http" or p.hostname != config.host or p.port != config.http_port
            or p.path != "/gcode_upload" or p.username or p.password or p.fragment
            or not re.fullmatch(r"s=[A-Za-z0-9_-]+", p.query)):
        raise ProtocolError("Printer upload URL is outside the qualified LAN endpoint")
    return p.path + "?" + p.query


def post_once(config, target, data, name):
    boundary = "------------------------" + uuid.uuid4().hex
    body = multipart(data, name, boundary)
    headers = {"User-Agent": "AnycubicSlicerNext/1.3.9.4", "Accept": "*/*",
               "X-BBL-Client-Name": "AnycubicSlicerNext", "X-BBL-Client-Type": "slicer",
               "X-BBL-Client-Version": "01.03.09.04", "X-BBL-Device-ID": str(uuid.uuid4()),
               "X-BBL-Language": "en-US", "X-BBL-OS-Type": "linux", "X-BBL-OS-Version": "Debian",
               "X-File-Length": str(len(data)), "Content-Type": f"multipart/form-data; boundary={boundary}",
               "Content-Length": str(len(body)), "Connection": "close"}
    # http.client does not retry or follow redirects. No print flag, no MQTT start.
    conn = http.client.HTTPConnection(config.host, config.http_port, timeout=180)
    try:
        conn.request("POST", target, body=body, headers=headers)
        response = conn.getresponse()
        raw = response.read(1024 * 1024 + 1)
        if not 200 <= response.status < 300 or len(raw) > 1024 * 1024:
            raise ProtocolError("Upload HTTP result is uncertain; do not retry")
        try:
            result = json.loads(raw)
        except ValueError:
            raise ProtocolError("Upload response is not JSON; do not retry") from None
        if not isinstance(result, dict):
            raise ProtocolError("Upload response has unknown shape; do not retry")
        return response.status, result
    finally:
        conn.close()


def reserve(directory, manifest):
    directory.mkdir(parents=True, exist_ok=True, mode=0o700)
    directory.chmod(0o700)
    marker = directory / (manifest["sha256"] + ".attempt")
    try:
        fd = os.open(marker, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    except FileExistsError:
        raise ProtocolError("This file already has an upload attempt; inspect its receipt, do not resend") from None
    with os.fdopen(fd, "w") as stream:
        stream.write(json.dumps(manifest) + "\n")
        stream.flush()
        os.fsync(stream.fileno())
    parent = os.open(directory, os.O_RDONLY | os.O_DIRECTORY)
    try:
        os.fsync(parent)
    finally:
        os.close(parent)
    return directory / (manifest["sha256"] + ".json")


def execute(config, path, expected_sha256, state_dir, remote_name=None):
    data, manifest = describe(path, remote_name)
    if manifest["sha256"] != expected_sha256:
        raise ProtocolError("File SHA-256 differs from reviewed manifest")
    device = hashlib.sha256(config.printer_id.encode()).hexdigest()[:16]
    directory = Path(state_dir) / device
    if (directory / (manifest["sha256"] + ".attempt")).exists():
        raise ProtocolError("Upload already attempted; no network write was repeated")
    with MQTT(config) as client:
        info = payload_data(client.query("info"))
        if info.get("model") != "Anycubic Kobra X" or info.get("version") != "2.0.2.2":
            raise ProtocolError("Device model/firmware is outside the qualified upload configuration")
        before = info
        # FW 2.0.2.2 reports free in info/report; print/query gives no report idle.
        if info.get("state") != "free" or info.get("project"):
            raise ProtocolError("Printer is not in a qualified idle print state; upload blocked")
        records = list_files(client)
        if any(r.get("filename") == manifest["remote_filename"] for r in records):
            raise ProtocolError("Remote filename already exists; no overwrite was attempted")
        url = (info.get("urls") or {}).get("fileUploadurl", "")
        target = upload_target(config, url)
        receipt = {**manifest, "timestamp": int(time.time()), "host": config.host,
                   "status": "attempt_reserved", "before": sanitized(before)}
        receipt_path = reserve(directory, manifest)
        atomic_json(receipt_path, receipt)
        try:
            status, result = post_once(config, target, data, manifest["remote_filename"])
            if result.get("code") != 200:
                raise ProtocolError("Printer did not return its qualified upload success code")
            # Only non-secret response fields are persisted or printed.
            receipt["http_status"] = status
            receipt["response"] = {k: result[k] for k in ["code", "status", "success"] if k in result}
            receipt["response_data_fields"] = sorted(result.get("data", {}).keys()) if isinstance(result.get("data"), dict) else []
            receipt["status"] = "http_response_received_unverified"
            atomic_json(receipt_path, receipt)
            # Only reads may be polled. Never repeat the HTTP POST.
            records = list_files(client)
            matches = [r for r in records if r.get("filename") == manifest["remote_filename"]]
            if len(matches) != 1 or matches[0].get("size") != len(data):
                raise ProtocolError("Remote file presence/size not confirmed")
            receipt["remote_listing"] = matches[0]
            details = safe_file_details(file_details(client, manifest["remote_filename"]))
            receipt["remote_details"] = details
            if (details.get("file_size") != len(data)
                    or details.get("layer_count") != manifest["layer_count"]
                    or details.get("printer_model") != "Anycubic Kobra X"):
                raise ProtocolError("Remote metadata does not match the reviewed file")
            after = payload_data(client.query("info"))
            receipt["after"] = sanitized(after)
            receipt["active_project_after"] = sanitized(after.get("project") or {})
            receipt["status"] = "uploaded_verified_by_listing_and_metadata"
            receipt["remote_byte_hash_verified"] = False
            atomic_json(receipt_path, receipt)
        except Exception:
            receipt["status"] = "uncertain_no_retry"
            atomic_json(receipt_path, receipt)
            raise ProtocolError("Upload/verification is uncertain; attempt recorded, do not resend") from None
        return {**receipt, "receipt_path": str(receipt_path)}
